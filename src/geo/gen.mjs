import {createRequire} from 'module';const require=createRequire(import.meta.url);
const topo=require('topojson-client');const d3=require('d3-geo');const t=require('./node_modules/es-atlas/es/provinces.json');
const MAP={'01':'VI','02':'AB','03':'A','04':'AL','05':'AV','06':'BA','07':'PM','08':'B','09':'BU','10':'CC','11':'CA','12':'CS','13':'CR','14':'CO','15':'AC','16':'CU','17':'GI','18':'GR','19':'GU','20':'SS','21':'H','22':'HU','23':'J','24':'LE','25':'LL','26':'LO','27':'LU','28':'M','29':'MA','30':'MU','31':'NA','32':'OR','33':'AS','34':'P','35':'GC','36':'PO','37':'SA','38':'TF','39':'CB','40':'SG','41':'SE','42':'SO','43':'T','44':'TE','45':'TO','46':'V','47':'VA','48':'BI','49':'ZA','50':'Z','51':'CE','52':'ME'};
const fc=topo.feature(t,t.objects.provinces);
const feats=fc.features.filter(f=>MAP[f.id]);
const pen=feats.filter(f=>!['35','38'].includes(f.id));
const can=feats.filter(f=>['35','38'].includes(f.id));
const W=800,H=640;
const penFC={type:'FeatureCollection',features:pen};
const proj=d3.geoConicConformal().parallels([36,43]).rotate([3.7,0]).fitExtent([[10,10],[W-10,H-90]],penFC);
const gp=d3.geoPath(proj).digits?d3.geoPath(proj).digits(1):d3.geoPath(proj);
const paths={},cent={};
pen.forEach(f=>{paths[MAP[f.id]]=gp(f);cent[MAP[f.id]]=gp.centroid(f).map(v=>Math.round(v*10)/10);});
const canFC={type:'FeatureCollection',features:can};
const box=[14,H-100,250,86];
const pc=d3.geoMercator().fitExtent([[box[0]+6,box[1]+6],[box[0]+box[2]-6,box[1]+box[3]-6]],canFC);
const gc=d3.geoPath(pc).digits(1);
can.forEach(f=>{paths[MAP[f.id]]=gc(f);cent[MAP[f.id]]=gc.centroid(f).map(v=>Math.round(v*10)/10);});
const out={w:W,h:H,paths,cent,canBox:box};
require('fs').writeFileSync('/home/claude/v3/geo/spain.json',JSON.stringify(out));
console.log(Object.keys(paths).length,JSON.stringify(out).length);
